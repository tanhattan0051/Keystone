// UpdateInstallScript.swift — pure builder for the shell script that swaps
// a verified update into place after Keystone quits. See DECISIONS.md
// "Updater: atomic swap with rollback".
//
// Keystone is the user's only input method, so the swap must never leave
// /Applications without a working bundle. The old script did `rm -rf
// <installed>; ditto <new> <installed>` with no error handling; a failed
// ditto (disk full, permissions) deleted the app. This script instead:
//   1. copies the new bundle to a SIBLING temp path (same volume, so the
//      later `mv` is an atomic rename),
//   2. re-verifies that copy (codesign + bundle id + version),
//   3. moves the old bundle aside, moves the new one in, and only then
//      deletes the old one,
//   4. on ANY failure rolls the old bundle back and relaunches it.
//
// Pure: it only builds a String. App/Updater.swift writes and launches it;
// UpdateInstallScriptTests runs it for real against fake bundles.

import Foundation

public enum UpdateInstallScript {
    /// Single-quotes `s` for a POSIX shell: wraps in `'...'` and rewrites
    /// each embedded `'` as `'\''`. Safe for spaces, `$`, backticks, etc.
    public static func shellQuoted(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// Builds the install script. Every interpolated value goes through
    /// `shellQuoted`; the script body itself contains no caller data.
    public static func make(
        waitForPID: Int32,
        stagedAppPath: String,
        installedAppPath: String,
        workDirPath: String,
        expectedBundleIdentifier: String,
        expectedVersion: String,
        logFilePath: String,
        relaunchCommand: String = "/usr/bin/open",
        waitTimeoutSeconds: Int = 60
    ) -> String {
        // Poll every 0.2s, so N seconds = N * 5 polls. Never below 1 poll.
        let maxPolls = max(1, waitTimeoutSeconds * 5)
        let q = shellQuoted

        return """
        #!/bin/bash
        # Generated by Keystone's updater. Swaps the verified update in
        # atomically and rolls back on any failure.
        set -euo pipefail

        WAIT_PID=\(waitForPID)
        MAX_POLLS=\(maxPolls)
        STAGED=\(q(stagedAppPath))
        INSTALLED=\(q(installedAppPath))
        WORKDIR=\(q(workDirPath))
        EXPECTED_ID=\(q(expectedBundleIdentifier))
        EXPECTED_VERSION=\(q(expectedVersion))
        LOG=\(q(logFilePath))
        RELAUNCH=\(q(relaunchCommand))

        # Siblings of the installed app: same directory, hence same volume,
        # hence an atomic rename for the final mv.
        PARENT="$(/usr/bin/dirname "$INSTALLED")"
        NEW="$PARENT/.Keystone-update-new-$$.app"
        OLD="$PARENT/.Keystone-update-old-$$.app"

        # If the log directory cannot be created, keep going silently rather
        # than abort: the app has already quit, and the swap must still run.
        if /bin/mkdir -p "$(/usr/bin/dirname "$LOG")" 2>/dev/null; then
            exec >>"$LOG" 2>&1
        else
            exec >/dev/null 2>&1
        fi

        log() { echo "$(/bin/date '+%Y-%m-%dT%H:%M:%S') $*"; }

        OLD_MOVED=0
        TIMED_OUT=0

        cleanup() {
            local rc=$?
            set +e
            trap - EXIT

            # Old bundle moved aside but nothing sits at INSTALLED: put it back.
            if [ "$OLD_MOVED" = 1 ] && [ ! -e "$INSTALLED" ] && [ -e "$OLD" ]; then
                log "ROLLBACK: restoring previous bundle"
                if ! /bin/mv "$OLD" "$INSTALLED"; then
                    log "ERROR: rollback mv failed; previous bundle remains at $OLD"
                fi
            fi

            if [ -e "$NEW" ]; then
                /bin/rm -rf "$NEW" || log "WARNING: could not remove leftover $NEW"
            fi

            # Relaunch whatever is installed now (new on success, old on
            # failure) - except when the old app never quit: launching then
            # would just focus the still-running instance, and we did not swap.
            if [ "$TIMED_OUT" = 1 ]; then
                log "Not relaunching: previous app was still running"
            elif [ -e "$INSTALLED" ]; then
                log "Relaunching $INSTALLED"
                "$RELAUNCH" "$INSTALLED" || log "WARNING: relaunch command failed"
            else
                log "ERROR: nothing installed at $INSTALLED to relaunch"
            fi

            # The work dir holds the staged app, the zip and this script.
            /bin/rm -rf "$WORKDIR" || log "WARNING: could not remove work dir $WORKDIR"

            log "Finished with exit code $rc"
            exit "$rc"
        }
        trap cleanup EXIT
        trap 'exit 143' HUP INT TERM

        log "Update started: expecting $EXPECTED_ID $EXPECTED_VERSION, waiting for pid $WAIT_PID"

        polls=0
        while kill -0 "$WAIT_PID" 2>/dev/null; do
            if [ "$polls" -ge "$MAX_POLLS" ]; then
                TIMED_OUT=1
                log "ERROR: pid $WAIT_PID still running after wait timeout; not swapping"
                exit 1
            fi
            /bin/sleep 0.2
            polls=$((polls + 1))
        done
        log "App exited; copying staged bundle next to installed one"

        /usr/bin/ditto "$STAGED" "$NEW"

        log "Verifying copied bundle"
        /usr/bin/codesign --verify --deep --strict "$NEW"
        FOUND_ID="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$NEW/Contents/Info.plist")"
        FOUND_VERSION="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$NEW/Contents/Info.plist")"
        if [ "$FOUND_ID" != "$EXPECTED_ID" ] || [ "$FOUND_VERSION" != "$EXPECTED_VERSION" ]; then
            log "ERROR: copied bundle is $FOUND_ID $FOUND_VERSION, expected $EXPECTED_ID $EXPECTED_VERSION"
            exit 1
        fi

        log "Swapping bundles"
        OLD_MOVED=1
        /bin/mv "$INSTALLED" "$OLD"
        /bin/mv "$NEW" "$INSTALLED"

        log "Swap complete; removing previous bundle"
        /bin/rm -rf "$OLD" || log "WARNING: could not remove previous bundle $OLD"
        exit 0
        """
    }
}
